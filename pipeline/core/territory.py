"""The Statistical Office of Serbia's territory tree, with codes.

pipeline/data/rzs_territory.json is generated by scripts/refresh_territory.py and committed. Every table the
pipeline reads joins on these ids, so this is the one place that knows how the ids are built:

* a 5-digit numeric id is a territorial unit: an opština, a grad, a grad's city municipality, or Grad Beograd;
* a 6-digit numeric id is a naselje (settlement) inside a unit;
* ``RS…`` ids are the country, its two halves, the regions (NUTS-2) and the oblasti (NUTS-3).
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

from .srtext import fold_key

TERRITORY_FILE = Path(__file__).resolve().parents[1] / "data" / "rzs_territory.json"
GRAD_BEOGRAD = "79014"
BEOGRAD_OBLAST = "RS110"


@lru_cache(maxsize=1)
def load() -> dict:
    """The committed file: {source, retrieved, datasets, levels, nodes: {id: {name, parent, level, children}}}."""
    return json.loads(TERRITORY_FILE.read_text(encoding="utf-8"))


def nodes() -> dict[str, dict]:
    return load()["nodes"]


def is_unit(unit_id) -> bool:
    """True for a 5-digit territorial unit (not a settlement, not a region)."""
    return isinstance(unit_id, str) and len(unit_id) == 5 and unit_id.isdigit()


def is_settlement(unit_id) -> bool:
    return isinstance(unit_id, str) and len(unit_id) == 6 and unit_id.isdigit()


def name(unit_id: str) -> str:
    return nodes()[unit_id]["name"]


def children(unit_id: str | None) -> list[str]:
    """Direct child ids, in the file's order."""
    return [k for k, v in nodes().items() if v["parent"] == unit_id]


def chain(unit_id: str) -> list[str]:
    """The node and its ancestors, nearest first: [unit, oblast, region, half, country]."""
    out, seen = [], 0
    while unit_id in nodes() and seen < 10:
        out.append(unit_id)
        unit_id = nodes()[unit_id]["parent"]
        seen += 1
    return out


def level(unit_id: str) -> int:
    return nodes()[unit_id]["level"]


def oblast_of(unit_id: str) -> str | None:
    """The NUTS-3 id (RS…) a unit or settlement lies in, or None when it is not under one."""
    return next((k for k in chain(unit_id) if level(k) == 3), None)


def in_kosovo(unit_id: str) -> bool:
    """True for anything under the Region Kosovo i Metohija (RS23)."""
    return "RS23" in chain(unit_id)


def aggregates() -> list[str]:
    """Grad Beograd and every grad published as the sum of its city municipalities, in id order."""
    return sorted(k for k in nodes() if is_unit(k) and (k == GRAD_BEOGRAD or any(is_unit(c) for c in children(k))))


def parts_of(unit_id: str) -> list[str]:
    """The units an aggregate is the sum of: Belgrade's 17 city municipalities, or the grad's own 5-digit children.
    A unit that is not an aggregate is its own only part."""
    if unit_id == GRAD_BEOGRAD:
        return sorted(k for k in children(BEOGRAD_OBLAST) if is_unit(k) and k != GRAD_BEOGRAD)
    parts = [c for c in children(unit_id) if is_unit(c)]
    return parts or [unit_id]


def is_city_municipality(unit_id: str) -> bool:
    """True for the 17 opštine of Grad Beograd and for a grad's 5-digit sub-units (Niš's Medijana, Kostolac…)."""
    if unit_id not in nodes() or not is_unit(unit_id):
        return False
    parent = nodes()[unit_id]["parent"]
    return parent == BEOGRAD_OBLAST and unit_id != GRAD_BEOGRAD or is_unit(parent)


@lru_cache(maxsize=1)
def _aggregate_of() -> dict[str, str]:
    """The aggregate a unit is a part of: Grad Beograd for its seventeen opštine, the grad for a city municipality."""
    out: dict[str, str] = {}
    for agg in aggregates():
        for part in parts_of(agg):
            out[part] = agg
    return out


def aggregate_of(unit_id: str) -> str | None:
    return _aggregate_of().get(unit_id)


def data_unit(unit_id: str, has_rows) -> str:
    """The unit whose published figures stand for `unit_id` in one source.

    ``has_rows(unit_id) -> bool`` says whether that source publishes the unit's own row. A unit with a row stands
    for itself. A unit without one inherits its aggregate's row in exactly one case: the aggregate has a row, no
    other part has one, and this is the first such part in id order. So Grad Novi Sad's figures (the census of 2022
    has the grad, not its two city municipalities) are counted once, on the first part, and never twice; and
    Belgrade's opštine, which each have their own row, never inherit. Anything else stands for itself, with no data.
    """
    if has_rows(unit_id):
        return unit_id
    agg = aggregate_of(unit_id)
    if agg is None or not has_rows(agg):
        return unit_id
    parts = sorted(parts_of(agg))
    if unit_id == parts[0] and not any(has_rows(p) for p in parts):
        return agg
    return unit_id


def row_for(table: dict, unit_id: str):
    """The row of a source's {unit id: row} table that stands for a unit, or None when it has none.

    A unit's own row stands for it, current or stale. In one case the aggregate's row replaces the parts': the
    aggregate is current (has_current) and no part is. The office has estimated Grad Novi Sad alone since 2020 and
    the census of 2022 counted the grad, not its two city municipalities; the grad's comparable row then stands for
    the first part in id order, once, and the other parts have none, so the stale rows of the parts are never summed
    with it and a figure is never counted twice."""
    agg = aggregate_of(unit_id)
    if agg is not None and has_current(table, agg) and not any(has_current(table, p) for p in parts_of(agg)):
        return table[agg] if unit_id == sorted(parts_of(agg))[0] else None
    return table.get(unit_id)


def has_current(table: dict, unit_id: str) -> bool:
    """Whether a source's {unit id: row} table publishes a current figure for the unit: a row whose latest value
    is not None. The office stopped estimating Novi Sad's two city municipalities after 2019 and publishes Grad
    Novi Sad instead, so their rows end in None and are not current; the grad's comparable series then stands for
    the first part, once (data_unit), and the stale rows of the parts are not summed with it."""
    row = table.get(unit_id)
    if row is None:
        return False
    if isinstance(row, list):
        return bool(row) and row[-1] is not None
    if isinstance(row, dict):
        if "total" in row:
            return row["total"] is not None
        return any(v is not None for v in row.values())
    return True


def units() -> list[str]:
    """Every 5-digit territorial unit, in id order: 204 today (175 with statistics, 29 in Kosovo and Metohija)."""
    return sorted(k for k in nodes() if is_unit(k))


def find_unit(name_text: str, parent: str | None = None) -> str | None:
    """The unit whose folded name equals `name_text` (optionally a child of `parent`), or None.
    Raises ValueError when the name is ambiguous."""
    key = fold_key(name_text)
    hits = [k for k in units() if fold_key(name(k)) == key and (parent is None or nodes()[k]["parent"] == parent)]
    if len(hits) > 1:
        raise ValueError(f"{name_text!r} matches {len(hits)} units under {parent}: {hits}")
    return hits[0] if hits else None
