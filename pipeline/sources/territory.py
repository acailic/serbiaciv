"""Catalog entry for the territory tree: where every territorial id the pipeline joins on comes from.

pipeline/data/rzs_territory.json is generated by scripts/refresh_territory.py from the territory trees the Statistical
Office's dissemination database embeds in its result pages, and committed. The pipeline itself fetches nothing; the
entry exists so that sources.json, the Almanac's bibliography, names the pages the tree was read from. Unlike a source
typed in from a screen, these pages were downloaded: the manifest under data/raw/rzs_territory lists the eleven pages
with their sha256, so the bibliography cites all of them (a `_files` of None means "every file in the manifest").
"""

from __future__ import annotations

from ..core.source import SourceInfo
from .sites import Curated

DATASETS = "https://data.stat.gov.rs/Home/Result/{subarea}?languageCode=sr-Latn"


class RzsTerritoryTree(Curated):
    vintage = "stablo teritorije preuzeto novembar 2026"
    info = SourceInfo(
        id="rzs_territory",
        title="Teritorijalna organizacija: okruzi, opštine, gradovi i naselja",
        publisher="Republički zavod za statistiku",
        homepage="https://data.stat.gov.rs/",
        license="© Republički zavod za statistiku; citirano uz navođenje izvora",
        description=(
            "Stablo teritorije iz Diseminacione baze podataka Republičkog zavoda za statistiku sa šiframa prostornih jedinica: "
            "sve tabele koje se učitavaju spajaju se po ovim šiframa. Kosovo i Metohija je u stablu, a statistika za njega "
            "ostaje prazna."
        ),
        used_for=["Teritorijalna organizacija (okruzi, opštine, naselja)", "Svi slojevi i paneli"],
    )

    def process(self) -> dict:
        # The pages are in the manifest (downloaded by the refresh script): cite all of them, as a fetched source would.
        return {"vintage": self.vintage, "_files": None}
